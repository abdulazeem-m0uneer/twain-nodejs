// Writes generated/layout_table.h: the C side of every constant, type and
// structure member that lib/twainh.js exports, so layout.c can report what
// the C compiler makes of twain.h for the very same names.
const fs = require("fs");
const path = require("path");
const twain = require("../../lib/twainh");
const constants = require("../../lib/constants");

const { koffi } = twain;

const typeNames = Object.keys(twain).filter(
  name =>
    twain[name] instanceof koffi.TypeObject &&
    twain[name].primitive !== "Prototype"
);

// Unions are anonymous in twain.h, so their members sit directly in the
// enclosing structure: measure the union's offset through its first member.
function cMemberName(member) {
  return member.type.primitive === "Union"
    ? Object.keys(member.type.members)[0]
    : member.name;
}

const offsetRows = typeNames
  .filter(name => twain[name].primitive === "Record")
  .flatMap(name =>
    Object.values(twain[name].members).map(
      member =>
        `  { "${name}", "${member.name}", offsetof(${name}, ${cMemberName(member)}) },`
    )
  );

const header = `/* Generated by generate.js - do not edit. */
static const Constant kConstants[] = {
${Object.keys(constants).map(name => `  { "${name}", (double)(${name}) },`).join("\n")}
};

static const TypeSize kSizes[] = {
${typeNames.map(name => `  { "${name}", sizeof(${name}) },`).join("\n")}
};

static const MemberOffset kOffsets[] = {
${offsetRows.join("\n")}
};
`;

const outDir = path.join(__dirname, "generated");
fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(path.join(outDir, "layout_table.h"), header);
